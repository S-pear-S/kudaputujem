-- Nedeterministički unaccent ne sme u indeks; pravimo IMMUTABLE omotač.
--
-- Đ/đ se zamenjuje RUČNO pre unaccent-a: unaccent daje 'd', a srpska
-- transliteracija je 'dj'. Python `normalize()` radi isto — test
-- tests/test_sql_parity.py to proverava.
CREATE OR REPLACE FUNCTION norm_text(input text)
    RETURNS text
    LANGUAGE sql
    IMMUTABLE
    PARALLEL SAFE
    STRICT
AS $$
SELECT btrim(
    regexp_replace(
        lower(
            public.unaccent(
                'public.unaccent',
                replace(replace(input, 'đ', 'dj'), 'Đ', 'Dj')
            )
        ),
        '[^a-z0-9]+', ' ', 'g'
    )
);
$$;

