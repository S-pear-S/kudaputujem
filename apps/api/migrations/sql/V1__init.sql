-- Cena za jednu kombinaciju sobe / slota. Ovo je srce domena.
--
-- Primeri iz stvarnosti:
--   "1/2 — 349 EUR po osobi"            → room_code=1/2,   capacity_adults=2, slot=ADULT,  basis=PER_PERSON_PER_STAY
--   "1/2+1 dete do 12 — 199 EUR"        → room_code=1/2+1, capacity_adults=2, extra_beds=1, slot=CHILD, child_age_to=11
--   "Apartman A2/4 — 60 EUR po danu"    → room_code=A2/4,  capacity_total=4, slot=UNIT,   basis=PER_UNIT_PER_NIGHT
CREATE TABLE price_option
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    departure_id      BIGINT      NOT NULL REFERENCES departure (id) ON DELETE CASCADE,
    offer_id          BIGINT      NOT NULL REFERENCES offer (id) ON DELETE CASCADE,
    -- opis sobe
    room_code         TEXT        NOT NULL,                  -- sirovo, kako piše agencija
    room_name         TEXT,
    capacity_adults   INT         NOT NULL DEFAULT 2,
    capacity_extra    INT         NOT NULL DEFAULT 0,        -- pomoćni ležajevi
    capacity_total    INT         NOT NULL DEFAULT 2,
    -- šta se plaća
    slot              TEXT        NOT NULL DEFAULT 'ADULT',  -- ADULT/CHILD/INFANT/EXTRA_BED/UNIT/SINGLE_SUPPLEMENT
    pricing_basis     TEXT        NOT NULL DEFAULT 'PER_PERSON_PER_STAY',
                                                             -- PER_PERSON_PER_STAY / PER_PERSON_PER_NIGHT
                                                             -- PER_UNIT_PER_STAY   / PER_UNIT_PER_NIGHT
    board_type        TEXT,
    child_age_from    INT,
    child_age_to      INT,
    -- iznos
    amount            NUMERIC(12, 2) NOT NULL,
    amount_rsd        NUMERIC(12, 2),
    currency          CHAR(3)     NOT NULL DEFAULT 'EUR',
    original_amount   NUMERIC(12, 2),                        -- cena pre popusta, ako je istaknuta
    discount_label    TEXT,                                  -- "first minute", "-20%"
    is_promo          BOOLEAN     NOT NULL DEFAULT FALSE,
    -- meta
    min_stay_nights   INT,
    notes             TEXT,
    last_seen_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_price_option_departure ON price_option (departure_id);
CREATE INDEX idx_price_option_offer ON price_option (offer_id);

